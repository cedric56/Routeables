using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;
using System.Collections.Immutable;
using System.Text;

namespace Routeables.Generated
{
    // Writing the generated source: one extension method per caller, and the route each one builds.
    public sealed partial class RouteCoordinationGenerator
    {

        private static void Emit(SourceProductionContext spc, ImmutableArray<AnalysisResult> results)
        {
            var methods = new List<NavMethod>();
            foreach (var result in results)
            {
                foreach (var d in result.Diagnostics)
                    spc.ReportDiagnostic(Diagnostic.Create(Descriptors[d.Id], d.Location?.ToLocation() ?? Location.None, d.Message));

                methods.AddRange(result.Methods);
            }

            var seen = new HashSet<string>(StringComparer.Ordinal);
            var accepted = new List<NavMethod>();
            foreach (var m in methods
                .OrderBy(m => m.CallerName, StringComparer.Ordinal)
                .ThenBy(m => m.MethodName, StringComparer.Ordinal)
                .ThenBy(m => m.DestinationName, StringComparer.Ordinal))
            {
                var signature = m.CallerName + "|" + m.MethodName + "|" + string.Join(",", m.Parameters.Select(p => p.TypeDisplay));
                if (!seen.Add(signature))
                {
                    spc.ReportDiagnostic(Diagnostic.Create(
                        Descriptors["ROUT107"],
                        m.Location?.ToLocation() ?? Location.None,
                        "The method " + m.MethodName + " is already generated for " + m.CallerName + " with the same parameter types: set MethodName on [RouteableViewModel] to tell them apart."));
                    continue;
                }

                accepted.Add(m);
            }

            foreach (var group in accepted.GroupBy(m => m.CallerName))
            {
                var first = group.First();
                spc.AddSource(
                    // The readable name is not unique ("A_B.C" and "A.B_C" give the same one, and a second file of the same name makes the compiler drop the
                    // generator): the hash of the full name of the caller tells them apart.
                    "RouteCoordination." + Sanitize(first.CallerHint) + "." + Hash(first.CallerName) + ".g.cs",
                    SourceText.From(EmitCaller(first, group.ToList()), Encoding.UTF8));
            }
        }

        private static string EmitCaller(NavMethod first, List<NavMethod> methods)
        {
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated />");
            sb.AppendLine("#nullable enable");
            sb.AppendLine();

            var indent = "";
            if (first.CallerNamespace.Length > 0)
            {
                sb.AppendLine("namespace " + first.CallerNamespace);
                sb.AppendLine("{");
                indent = "    ";
            }

            sb.AppendLine(indent + "internal static class " + first.CallerHint + "RouteCoordination");
            sb.AppendLine(indent + "{");
            // A surrogate without its pair would be written as U+FFFD, and the value read back would not be the one given (RouteParser.Build refuses it too).
            sb.AppendLine(indent + "    private static string __RouteEscape(string value)");
            sb.AppendLine(indent + "    {");
            sb.AppendLine(indent + "        for (var i = 0; i < value.Length; i++)");
            sb.AppendLine(indent + "        {");
            sb.AppendLine(indent + "            if (global::System.Char.IsHighSurrogate(value[i]) && i + 1 < value.Length && global::System.Char.IsLowSurrogate(value[i + 1])) i++;");
            sb.AppendLine(indent + "            else if (global::System.Char.IsSurrogate(value[i])) throw new global::System.ArgumentException(\"A route value is not valid Unicode text (a surrogate without its pair).\");");
            sb.AppendLine(indent + "        }");
            sb.AppendLine(indent + "        return global::System.Uri.EscapeDataString(value);");
            sb.AppendLine(indent + "    }");
            sb.AppendLine();

            for (var i = 0; i < methods.Count; i++)
            {
                if (i > 0)
                    sb.AppendLine();
                EmitMethod(sb, indent + "    ", methods[i]);
            }

            sb.AppendLine(indent + "}");

            if (first.CallerNamespace.Length > 0)
                sb.AppendLine("}");

            return sb.ToString();
        }

        private static void EmitMethod(StringBuilder sb, string indent, NavMethod m)
        {
            const string returnType = "global::System.Threading.Tasks.Task<global::Routeables.Abstraction.Routing.RouteableResult>";

            // Only a <summary>: a partial set of <param> tags would raise CS1573 in projects that treat warnings as errors.
            sb.AppendLine(indent + "/// <summary>Goes to <c>" + Xml(m.DestinationDisplay) + "</c> (route <c>" + Xml(m.Template) + "</c>).</summary>");
            sb.AppendLine(indent + "internal static " + returnType + " " + m.MethodName + "(");
            sb.AppendLine(indent + "    this " + m.CallerName + " caller,");
            sb.AppendLine(indent + "    global::Routeables.Abstraction.Routing.IRouter router,");
            foreach (var p in m.Parameters)
                sb.AppendLine(indent + "    " + p.Declaration + ",");
            sb.AppendLine(indent + "    global::System.Threading.CancellationToken cancellationToken = default)");
            sb.AppendLine(indent + "{");

            var body = indent + "    ";
            sb.AppendLine(body + "global::System.ArgumentNullException.ThrowIfNull(router);");
            foreach (var p in m.Parameters)
            {
                if (p.CheckNotEmpty)
                    sb.AppendLine(body + "global::System.ArgumentException.ThrowIfNullOrEmpty(" + p.Id + ");");
                else if (p.CheckNotNull)
                    sb.AppendLine(body + "global::System.ArgumentNullException.ThrowIfNull(" + p.Id + ");");
            }

            EmitRoute(sb, body, m);

            sb.AppendLine(body + "var __args = global::Routeables.Routing.RouteableArgs.Create();");
            foreach (var e in m.Entries)
            {
                var value = e.IsRouter ? "router" : e.ParamId;
                var statement = "__args.ForViewModel(new global::Routeables.Abstraction.Routing.RouteableArgument(" + value + "));";
                sb.AppendLine(body + (e.Conditional ? "if (" + value + " is not null) " : string.Empty) + statement);
            }

            sb.AppendLine(body + "return router.GoToAsync(__route, __args, " + Literal(m.Template) + ", cancellationToken);");
            sb.AppendLine(indent + "}");
        }

        private static void EmitRoute(StringBuilder sb, string indent, NavMethod m)
        {
            var expressions = new List<string>();
            var pending = new StringBuilder();
            if (m.LeadingSlash)
                pending.Append('/');

            var deferred = new List<RouteOp>();
            var queryOps = new List<RouteOp>();

            void Flush()
            {
                if (pending.Length == 0)
                    return;
                expressions.Add(Literal(pending.ToString()));
                pending.Clear();
            }

            foreach (var op in m.RouteOps)
            {
                switch (op.Kind)
                {
                    case RouteOpKind.PathLiteral:
                        pending.Append(op.Prefix).Append(op.Text);
                        break;
                    case RouteOpKind.PathParam when op.Optional:
                        deferred.Add(op);
                        break;
                    case RouteOpKind.PathParam:
                        pending.Append(op.Prefix);
                        Flush();
                        expressions.Add(Format(op.Clr, ValueOf(op), path: true));
                        break;
                    default:
                        queryOps.Add(op);
                        break;
                }
            }

            Flush();
            sb.AppendLine(indent + "var __route = " + (expressions.Count == 0 ? "\"\"" : string.Join(" + ", expressions)) + ";");

            // An optional placeholder is the last segment of the path (ROUT104), so there is no later value to be read in its place.
            foreach (var op in deferred)
            {
                var statement = "__route += " + Literal(op.Prefix) + " + " + Format(op.Clr, ValueOf(op), path: true) + ";";
                sb.AppendLine(indent + (op.Conditional ? "if (" + HasValue(op) + ") " : string.Empty) + statement);
            }

            if (queryOps.Count == 0)
            {
                // Only optional values, none given: the home address, as RouteParser.Build writes it (the router rejects an empty one).
                sb.AppendLine(indent + "if (__route.Length == 0) __route = \"/\";");
                return;
            }

            // A path of optional values left out, before a query, is "/?q=x", as RouteParser.Build writes it (a template with no path stays "?q=x").
            var hasPathParam = false;
            foreach (var op in m.RouteOps)
                if (op.Kind == RouteOpKind.PathParam)
                    hasPathParam = true;
            if (hasPathParam)
                sb.AppendLine(indent + "if (__route.Length == 0) __route = \"/\";");

            sb.AppendLine(indent + "var __separator = '?';");
            foreach (var op in queryOps)
            {
                if (op.Kind == RouteOpKind.QueryLiteral)
                {
                    sb.AppendLine(indent + "__route += __separator + " + Literal(op.Text) + ";");
                    sb.AppendLine(indent + "__separator = '&';");
                    continue;
                }

                var add = "{ __route += __separator + " + Literal(op.Text + "=") + " + " + Format(op.Clr, ValueOf(op)) + "; __separator = '&'; }";
                sb.AppendLine(indent + (op.Conditional ? "if (" + HasValue(op) + ") " : string.Empty) + add);
            }
        }

        // A value that is given: RouteParser.Build counts a null and an empty text as no value, and so does the code written here.
        private static string HasValue(RouteOp op) =>
            op.Clr is ClrKind.String or ClrKind.Rest
                ? "!global::System.String.IsNullOrEmpty(" + op.ParamId + ")"
                : op.ParamId + " is not null";

        private static string ValueOf(RouteOp op) => op.NullableValue ? op.ParamId + ".Value" : op.ParamId;

        private static string Format(ClrKind kind, string value, bool path = false)
        {
            switch (kind)
            {
                case ClrKind.Int:
                case ClrKind.Long:
                    return "global::System.Uri.EscapeDataString(" + value + ".ToString(global::System.Globalization.CultureInfo.InvariantCulture))";
                case ClrKind.Decimal:
                    // 19.90m is the text 19.9: a number has one text (RouteParser.Build writes the same).
                    return "global::System.Uri.EscapeDataString((" + value + " / 1.0000000000000000000000000000m).ToString(global::System.Globalization.CultureInfo.InvariantCulture))";
                case ClrKind.Double:
                    // -0.0 is the text 0.
                    // NaN and infinity are not numbers a route can read back (RouteParser.Build rejects them).
                    return "global::System.Uri.EscapeDataString((!global::System.Double.IsFinite(" + value + ") ? throw new global::System.ArgumentException(\"A route value cannot be NaN or infinity.\") : " + value + " == 0d ? 0d : " + value + ").ToString(global::System.Globalization.CultureInfo.InvariantCulture))";
                case ClrKind.Bool:
                    return "(" + value + " ? \"true\" : \"false\")";
                case ClrKind.Guid:
                    return "global::System.Uri.EscapeDataString(" + value + ".ToString())";
                case ClrKind.Rest:
                    // The rest of the path keeps its slashes and each piece is escaped, as in RouteParser.Build, which also rejects an empty piece, "." and "..".
                    return "(" + value + ".Length == 0 ? \"\" : global::System.String.Join(\"/\", global::System.Linq.Enumerable.Select(" + value
                        + ".Split('/'), new global::System.Func<string, string>(__piece => __piece.Length == 0 || __piece == \".\" || __piece == \"..\""
                        + " ? throw new global::System.ArgumentException(\"A catch-all value has no empty, \\\".\\\" or \\\"..\\\" segment.\") : __RouteEscape(__piece)))))";
                default:
                    // "." and ".." are not a path segment: a browser resolves them to another address (RouteParser.Build rejects them).
                    return path
                        ? "(global::System.Array.Exists(" + value + ".Split('/'), __part => __part is \".\" or \"..\") ? throw new global::System.ArgumentException(\"A path value cannot be \\\".\\\" or \\\"..\\\".\") : __RouteEscape(" + value + "))"
                        : "__RouteEscape(" + value + ")";
            }
        }

        private static string Literal(string value) => SymbolDisplay.FormatLiteral(value, quote: true);

        private static string Xml(string value) =>
            value.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");

        // FNV-1a over the characters, in hexadecimal: the same text always gives the same name, so the files do not change from one build to the next.
        private static string Hash(string value)
        {
            var hash = 2166136261u;
            foreach (var c in value)
                hash = unchecked((hash ^ c) * 16777619u);
            return hash.ToString("x8", System.Globalization.CultureInfo.InvariantCulture);
        }

        private static string Sanitize(string value)
        {
            var sb = new StringBuilder(value.Length);
            foreach (var c in value)
                sb.Append(char.IsLetterOrDigit(c) || c == '_' ? c : '_');
            return sb.ToString();
        }
    }
}
