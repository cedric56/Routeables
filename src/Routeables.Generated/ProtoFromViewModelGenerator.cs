[Generator]
public sealed class ProtoFromViewModelGenerator : IIncrementalGenerator
{
    private const string AttributeName =
    "Routeables.Generated.Abstraction.ProtoStateAttribute";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        //var viewModels = context.SyntaxProvider
        //    .ForAttributeWithMetadataName(
        //        AttributeName,
        //        predicate: static (node, _) => node is ClassDeclarationSyntax
        //            or RecordDeclarationSyntax,
        //        transform: static (ctx, ct) => Extract(ctx, ct))
        //    .Where(static vm => vm is not null)
        //    .WithTrackingName("Routeables_ProtoState");
        var viewModels = context.SyntaxProvider
    .ForAttributeWithMetadataName(
        AttributeName,
        predicate: static (node, _) =>
            node is ClassDeclarationSyntax,
        transform: static (ctx, ct) => Extract(ctx, ct))
    .Where(static vm => vm is not null);

        context.RegisterSourceOutput(viewModels, static (spc, vm) =>
        {
            var model = vm!.Value;

            spc.AddSource(
                GetHintName(model),
                GenerateContract(model));

            spc.AddSource(
                GetDispatcherHintName(model),
                GenerateDispatcher(model));
        });
    }

    private static string GetDispatcherHintName(VmModel vm)
    {
        return GetHintName(vm).Replace(
            "_Proto.g.cs",
            "_ProtoDispatcher.g.cs");
    }


    private static string GenerateDispatcher(VmModel vm)
    {
        var source = new StringBuilder();

        var viewModelType = string.IsNullOrWhiteSpace(vm.Namespace)
            ? $"global::{EscapeCSharpIdentifier(vm.ClassName)}"
            : $"global::{vm.Namespace}.{EscapeCSharpIdentifier(vm.ClassName)}";

        if (!string.IsNullOrWhiteSpace(vm.Namespace))
        {
            source.AppendLine($"namespace {vm.Namespace};");
            source.AppendLine();
        }

        source.AppendLine("// <auto-generated />");
        source.AppendLine("#nullable enable");
        source.AppendLine();
        source.AppendLine(
            $"public static class {EscapeCSharpIdentifier(vm.ClassName)}ProtoDispatcher");
        source.AppendLine("{");

        source.AppendLine(
            $"    public static async global::System.Threading.Tasks.Task ExecuteAsync(");
        source.AppendLine(
            $"        {viewModelType} viewModel,");
        source.AppendLine(
            "        string commandName,");
        source.AppendLine(
            "        string argsJson)");
        source.AppendLine("    {");

        source.AppendLine(
            "        using var document = global::System.Text.Json.JsonDocument.Parse(argsJson);");
        source.AppendLine(
            "        var args = document.RootElement;");

        source.AppendLine(
            "        if (args.ValueKind != global::System.Text.Json.JsonValueKind.Array)");
        source.AppendLine(
            "            throw new global::System.ArgumentException(\"Command arguments must be a JSON array.\", nameof(argsJson));");

        source.AppendLine();
        source.AppendLine("        switch (commandName)");
        source.AppendLine("        {");

        foreach (var command in vm.Commands)
        {
            source.AppendLine(
                $"            case {SymbolDisplay.FormatLiteral(command.Name, true)}:");

            source.AppendLine(
                $"                if (args.GetArrayLength() != {command.Parameters.Length})");

            source.AppendLine(
                "                    throw new global::System.ArgumentException(\"Invalid command argument count.\", nameof(argsJson));");

            var arguments = new List<string>();

            for (var i = 0; i < command.Parameters.Length; i++)
            {
                var parameter = command.Parameters[i];

                var variableName = $"arg{i}";

                source.AppendLine(
                    $"                var {variableName} = global::System.Text.Json.JsonSerializer.Deserialize<{parameter.TypeName}>(args[{i}].GetRawText())!;");

                arguments.Add(variableName);
            }

            var invocation =
                $"viewModel.{EscapeCSharpIdentifier(command.MethodName)}({string.Join(", ", arguments)})";

            if (command.ReturnsTask)
            {
                source.AppendLine(
                    $"                await {invocation};");
            }
            else
            {
                source.AppendLine(
                    $"                {invocation};");
            }

            source.AppendLine("                break;");
        }

        source.AppendLine("            default:");
        source.AppendLine(
            "                throw new global::System.InvalidOperationException($\"Unknown command: {commandName}\");");

        source.AppendLine("        }");
        source.AppendLine("    }");
        source.AppendLine("}");

        return source.ToString();
    }


    private readonly record struct ParameterModel(
    string Name,
    string TypeName);

    private readonly record struct CommandModel(
        string Name,
        string MethodName,
        bool ReturnsTask,
        ImmutableArray<ParameterModel> Parameters);

    private readonly record struct PropertyModel(
        string Name,
        string ProtoName,
        string ProtoType,
        int Index,
        bool IsCollection);

    private sealed class NestedMessageModel
    {
        public INamedTypeSymbol Symbol { get; set; } = null!;
        public string Name { get; set; } = string.Empty;
        public ImmutableArray<PropertyModel> Properties { get; set; }
            = ImmutableArray<PropertyModel>.Empty;
    }

    private readonly record struct VmModel(
    string ClassName,
    string Namespace,
    string FileName,
    string Package,
    string ServiceName,
    string StateMessageName,
    ImmutableArray<PropertyModel> Properties,
    ImmutableArray<NestedMessageModel> NestedMessages,
    ImmutableArray<CommandModel> Commands);

    private static VmModel? Extract(
        GeneratorAttributeSyntaxContext context,
        CancellationToken cancellationToken)
    {
        cancellationToken.ThrowIfCancellationRequested();

        if (context.TargetSymbol is not INamedTypeSymbol symbol)
            return null;

        var attribute = symbol.GetAttributes()
            .FirstOrDefault(a =>
                a.AttributeClass?.ToDisplayString() == AttributeName);

        if (attribute is null)
            return null;

        var fileName = "state.proto";
        var package = "routeables";
        string? service = null;
        string? stateMessage = null;

        if (attribute.ConstructorArguments.Length > 0 &&
            attribute.ConstructorArguments[0].Value is string file)
        {
            fileName = file;
        }

        foreach (var argument in attribute.NamedArguments)
        {
            switch (argument.Key)
            {
                case nameof(ProtoStateAttribute.Package)
                    when argument.Value.Value is string value:
                    package = value;
                    break;

                case nameof(ProtoStateAttribute.Service)
                    when argument.Value.Value is string value:
                    service = value;
                    break;

                case nameof(ProtoStateAttribute.StateMessage)
                    when argument.Value.Value is string value:
                    stateMessage = value;
                    break;
            }
        }

        stateMessage ??= $"{symbol.Name}State";

        var nestedMessages = new List<NestedMessageModel>();

        var properties = BuildProperties(
            symbol,
            symbol,
            stateMessage,
            nestedMessages,
            cancellationToken);

        var ns = symbol.ContainingNamespace?.IsGlobalNamespace == false
            ? symbol.ContainingNamespace.ToDisplayString()
            : string.Empty;

        var commands = GetCommands(symbol);

        return new VmModel(
            ClassName: symbol.Name,
            Namespace: ns,
            FileName: fileName,
            Package: package,
            ServiceName: service ?? symbol.Name,
            StateMessageName: stateMessage,
            Properties: properties,
            NestedMessages: nestedMessages.ToImmutableArray(),
            Commands: commands);
    }

    private const string ProtoCommandAttributeName =
    "Routeables.Generated.Abstraction.ProtoCommandAttribute";

    private static ImmutableArray<CommandModel> GetCommands(
        INamedTypeSymbol symbol)
    {
        var commands = ImmutableArray.CreateBuilder<CommandModel>();
        var usedNames = new HashSet<string>(StringComparer.Ordinal);

        for (var current = symbol;
             current is not null;
             current = current.BaseType)
        {
            foreach (var method in current.GetMembers()
                         .OfType<IMethodSymbol>())
            {
                if (method.MethodKind != MethodKind.Ordinary ||
                    method.IsStatic ||
                    method.DeclaredAccessibility != Accessibility.Public ||
                    method.IsGenericMethod ||
                    method.ReturnsByRef ||
                    method.ReturnsByRefReadonly)
                {
                    continue;
                }

                var attribute = method.GetAttributes()
                    .FirstOrDefault(a =>
                        a.AttributeClass?.ToDisplayString() ==
                        ProtoCommandAttributeName);

                if (attribute is null)
                    continue;

                // Support void, Task and Task<T>.
                var returnType = method.ReturnType;

                var returnsTask =
                    returnType.ToDisplayString() ==
                    "System.Threading.Tasks.Task" ||
                    returnType is INamedTypeSymbol namedReturn &&
                    namedReturn.OriginalDefinition.MetadataName == "Task`1" &&
                    namedReturn.OriginalDefinition.ContainingNamespace
                        .ToDisplayString() == "System.Threading.Tasks";

                var returnsVoid =
                    returnType.SpecialType == SpecialType.System_Void;

                if (!returnsTask && !returnsVoid)
                    continue;

                var parameters = ImmutableArray.CreateBuilder<ParameterModel>();
                var supported = true;

                foreach (var parameter in method.Parameters)
                {
                    if (parameter.RefKind != RefKind.None ||
                        parameter.IsParams)
                    {
                        supported = false;
                        break;
                    }

                    parameters.Add(new ParameterModel(
                        parameter.Name,
                        parameter.Type.ToDisplayString(
                            SymbolDisplayFormat.FullyQualifiedFormat)));
                }

                if (!supported)
                    continue;

                var commandName = method.Name;

                foreach (var namedArgument in attribute.NamedArguments)
                {
                    if (namedArgument.Key == "Name" &&
                        namedArgument.Value.Value is string customName &&
                        !string.IsNullOrWhiteSpace(customName))
                    {
                        commandName = customName;
                    }
                }

                if (!usedNames.Add(commandName))
                    continue;

                commands.Add(new CommandModel(
                    commandName,
                    method.Name,
                    returnsTask,
                    parameters.ToImmutable()));
            }
        }

        return commands.ToImmutable();
    }

    private static ImmutableArray<PropertyModel> BuildProperties(
        INamedTypeSymbol symbol,
        INamedTypeSymbol rootSymbol,
        string rootMessageName,
        List<NestedMessageModel> nestedMessages,
        CancellationToken cancellationToken)
    {
        var result = ImmutableArray.CreateBuilder<PropertyModel>();
        var usedNames = new HashSet<string>(System.StringComparer.Ordinal);

        foreach (var property in GetPublicProperties(symbol))
        {
            cancellationToken.ThrowIfCancellationRequested();

            if (!TryMapProperty(
                    property,
                    result.Count + 1,
                    rootSymbol,
                    rootMessageName,
                    nestedMessages,
                    out var mapped))
            {
                continue;
            }

            var protoName = mapped.ProtoName;
            var suffix = 2;

            while (!usedNames.Add(protoName))
                protoName = $"{mapped.ProtoName}_{suffix++}";

            result.Add(mapped with { ProtoName = protoName });
        }

        return result.ToImmutable();
    }

    private static bool TryMapProperty(
        IPropertySymbol property,
        int index,
        INamedTypeSymbol rootSymbol,
        string rootMessageName,
        List<NestedMessageModel> nestedMessages,
        out PropertyModel mapped)
    {
        mapped = default;

        var type = property.Type;

        // byte[] is a protobuf bytes field, not repeated uint32.
        if (type is IArrayTypeSymbol array &&
            array.ElementType.SpecialType == SpecialType.System_Byte)
        {
            mapped = Create(property.Name, "bytes", index, false);
            return true;
        }

        if (type.SpecialType == SpecialType.System_String)
        {
            mapped = Create(property.Name, "string", index, false);
            return true;
        }

        type = UnwrapNullable(type);

        var isCollection = TryGetEnumerableElement(type, out var elementType);

        if (isCollection)
            type = UnwrapNullable(elementType);

        var protoType = MapScalar(type);

        if (protoType is not null)
        {
            mapped = Create(property.Name, protoType, index, isCollection);
            return true;
        }

        // Unsupported scalar or complex type.
        if (type is not INamedTypeSymbol namedType ||
            (namedType.TypeKind != TypeKind.Class &&
             namedType.TypeKind != TypeKind.Struct))
        {
            return false;
        }

        // Avoid treating arbitrary framework types as nested messages.
        if (namedType.SpecialType != SpecialType.None ||
            namedType.IsTupleType)
        {
            return false;
        }

        string messageName;

        if (SymbolEqualityComparer.Default.Equals(namedType, rootSymbol))
        {
            // A reference back to the ViewModel points to its state message.
            messageName = rootMessageName;
        }
        else
        {
            messageName = EnsureNestedMessage(
                namedType,
                nestedMessages,
                rootSymbol,
                rootMessageName);
        }

        mapped = Create(property.Name, messageName, index, isCollection);
        return true;
    }

    private static string EnsureNestedMessage(
        INamedTypeSymbol symbol,
        List<NestedMessageModel> nestedMessages,
        INamedTypeSymbol rootSymbol,
        string rootMessageName)
    {
        var existing = nestedMessages.FirstOrDefault(
            m => SymbolEqualityComparer.Default.Equals(m.Symbol, symbol));

        if (existing is not null)
            return existing.Name;

        var usedNames = new HashSet<string>(
            nestedMessages.Select(m => m.Name),
            System.StringComparer.Ordinal)
        {
            rootMessageName,
            $"{rootSymbol.Name}Command",
            "Empty"
        };

        var baseName = SanitizeProtoIdentifier(symbol.Name);
        var name = baseName;
        var suffix = 2;

        while (!usedNames.Add(name))
            name = $"{baseName}_{suffix++}";

        // Register before traversing properties.
        // This is what makes circular references safe.
        var nested = new NestedMessageModel
        {
            Symbol = symbol,
            Name = name,
            Properties = ImmutableArray<PropertyModel>.Empty
        };

        nestedMessages.Add(nested);

        nested.Properties = BuildProperties(
            symbol,
            rootSymbol,
            rootMessageName,
            nestedMessages,
            default);

        return name;
    }

    private static ImmutableArray<IPropertySymbol> GetPublicProperties(
        INamedTypeSymbol symbol)
    {
        var properties = new Dictionary<string, IPropertySymbol>(
            System.StringComparer.Ordinal);

        for (var current = symbol;
             current is not null;
             current = current.BaseType)
        {
            foreach (var property in current.GetMembers()
                         .OfType<IPropertySymbol>())
            {
                if (property.IsStatic ||
                    property.IsIndexer ||
                    property.DeclaredAccessibility != Accessibility.Public ||
                    property.GetMethod?.DeclaredAccessibility != Accessibility.Public)
                {
                    continue;
                }

                if (!properties.ContainsKey(property.Name))
                {
                    properties.Add(property.Name, property);
                }
            }
        }

        return properties.Values
            .OrderBy(p => p.Name, System.StringComparer.Ordinal)
            .ToImmutableArray();
    }

    private static PropertyModel Create(
        string name,
        string protoType,
        int index,
        bool isCollection)
    {
        return new PropertyModel(
            Name: name,
            ProtoName: SanitizeProtoIdentifier(ToSnakeCase(name)),
            ProtoType: protoType,
            Index: index,
            IsCollection: isCollection);
    }

    private static ITypeSymbol UnwrapNullable(ITypeSymbol type)
    {
        if (type is INamedTypeSymbol named &&
            named.OriginalDefinition.SpecialType ==
            SpecialType.System_Nullable_T)
        {
            return named.TypeArguments[0];
        }

        return type;
    }

    private static bool TryGetEnumerableElement(
        ITypeSymbol type,
        out ITypeSymbol elementType)
    {
        elementType = null!;

        if (type is IArrayTypeSymbol array)
        {
            elementType = array.ElementType;
            return true;
        }

        if (type is not INamedTypeSymbol named)
            return false;

        if (IsGenericEnumerable(named))
        {
            elementType = named.TypeArguments[0];
            return true;
        }

        var enumerable = named.AllInterfaces
            .OfType<INamedTypeSymbol>()
            .FirstOrDefault(IsGenericEnumerable);

        if (enumerable is null)
            return false;

        elementType = enumerable.TypeArguments[0];
        return true;
    }

    private static bool IsGenericEnumerable(INamedTypeSymbol type)
    {
        return type.OriginalDefinition.MetadataName == "IEnumerable`1" &&
               type.OriginalDefinition.ContainingNamespace.ToDisplayString() ==
               "System.Collections.Generic";
    }

    private static string? MapScalar(ITypeSymbol type)
    {
        if (type.TypeKind == TypeKind.Enum)
            return "int32";

        return type.SpecialType switch
        {
            SpecialType.System_String => "string",
            SpecialType.System_Boolean => "bool",

            SpecialType.System_Byte => "uint32",
            SpecialType.System_SByte => "int32",
            SpecialType.System_Int16 => "int32",
            SpecialType.System_UInt16 => "uint32",
            SpecialType.System_Int32 => "int32",
            SpecialType.System_UInt32 => "uint32",
            SpecialType.System_Int64 => "int64",
            SpecialType.System_UInt64 => "uint64",

            SpecialType.System_Single => "float",
            SpecialType.System_Double => "double",
            SpecialType.System_Char => "uint32",

            _ => null
        };
    }

    private static string GenerateContract(VmModel vm)
    {
        var stateMessageName =
            SanitizeProtoIdentifier(vm.StateMessageName);

        var commandName =
            SanitizeProtoIdentifier(vm.ClassName) + "Command";

        var serviceName =
            SanitizeProtoIdentifier(vm.ServiceName);

        var protoNamespace = string.IsNullOrWhiteSpace(vm.Namespace)
            ? "Proto"
            : $"{vm.Namespace}.Proto";

        var messages = new StringBuilder();

        AppendMessage(
            messages,
            stateMessageName,
            vm.Properties);

        foreach (var nested in vm.NestedMessages)
        {
            messages.AppendLine();
            AppendMessage(
                messages,
                nested.Name,
                nested.Properties);
        }

        var proto = new StringBuilder();

        proto.AppendLine("syntax = \"proto3\";");
        proto.AppendLine();
        proto.AppendLine(
            $"package {SanitizeQualifiedProtoName(vm.Package)};");
        proto.AppendLine();
        proto.AppendLine(
            $"option csharp_namespace = \"{EscapeProtoString(protoNamespace)}\";");
        proto.AppendLine();
        proto.AppendLine($"// État sérialisé de {vm.ClassName}");
        proto.Append(messages);
        proto.AppendLine();
        proto.AppendLine($"// Commande adressée à {vm.ClassName}");
        proto.AppendLine($"message {commandName} {{");
        proto.AppendLine("  string name = 1;");
        proto.AppendLine("  string args_json = 2;");
        proto.AppendLine("}");
        proto.AppendLine();
        proto.AppendLine("message Empty {}");
        proto.AppendLine();
        proto.AppendLine($"service {serviceName} {{");
        proto.AppendLine(
            $"  rpc SubscribeToState (Empty) returns (stream {stateMessageName});");
        proto.AppendLine(
            $"  rpc ExecuteCommand ({commandName}) returns (Empty);");
        proto.AppendLine("}");

        var className = EscapeCSharpIdentifier(vm.ClassName);

        var source = new StringBuilder();

        source.AppendLine(
            "// <auto-generated>Generated by Routeables.Generated. Do not modify.</auto-generated>");
        source.AppendLine("#nullable enable");
        source.AppendLine();

        if (!string.IsNullOrWhiteSpace(vm.Namespace))
        {
            source.AppendLine($"namespace {vm.Namespace};");
            source.AppendLine();
        }

        source.AppendLine(
            $"/// <summary>Proto contract generated from {vm.ClassName}.</summary>");
        source.AppendLine($"public static class {className}Proto");
        source.AppendLine("{");

        source.AppendLine(
            $"    public const string FileName = {SymbolDisplay.FormatLiteral(vm.FileName, quote: true)};");

        source.AppendLine(
            $"    public const string Package = {SymbolDisplay.FormatLiteral(vm.Package, quote: true)};");

        source.AppendLine(
            $"    public const string ServiceName = {SymbolDisplay.FormatLiteral(vm.ServiceName, quote: true)};");

        source.AppendLine(
            $"    public const string StateMessageName = {SymbolDisplay.FormatLiteral(vm.StateMessageName, quote: true)};");

        source.AppendLine();

        // Utiliser une chaîne verbatim C# pour contenir le contrat Protobuf.
        // Les guillemets internes sont doublés.
        source.AppendLine("    public const string Text = @\"");

        foreach (var line in proto.ToString().Split('\n'))
        {
            var normalizedLine = line.TrimEnd('\r');
            source.Append("    ");
            source.Append(normalizedLine.Replace("\"", "\"\""));
            source.AppendLine();
        }

        source.AppendLine("    \";");
        source.AppendLine("}");

        return source.ToString();
    }

    private static void AppendMessage(
        StringBuilder builder,
        string name,
        ImmutableArray<PropertyModel> properties)
    {
        builder.AppendLine($"message {name} {{");

        foreach (var property in properties)
        {
            builder.Append("  ");

            if (property.IsCollection)
                builder.Append("repeated ");

            builder.Append(property.ProtoType)
                .Append(' ')
                .Append(property.ProtoName)
                .Append(" = ")
                .Append(property.Index)
                .AppendLine(";");
        }

        builder.AppendLine("}");
    }

    private static string GetHintName(VmModel vm)
    {
        var fullName = string.IsNullOrEmpty(vm.Namespace)
            ? vm.ClassName
            : $"{vm.Namespace}.{vm.ClassName}";

        var safeName = new string(fullName
            .Select(c => char.IsLetterOrDigit(c) ? c : '_')
            .ToArray());

        var hash = unchecked((uint)StringComparer.Ordinal.GetHashCode(fullName));

        return $"{safeName}_{hash:X8}_Proto.g.cs";
    }

    private static string ToSnakeCase(string name)
    {
        var sb = new StringBuilder();

        for (var i = 0; i < name.Length; i++)
        {
            var current = name[i];

            if (char.IsUpper(current))
            {
                var previousIsLowerOrDigit =
                    i > 0 &&
                    (char.IsLower(name[i - 1]) || char.IsDigit(name[i - 1]));

                var nextIsLower =
                    i + 1 < name.Length && char.IsLower(name[i + 1]);

                if (i > 0 && (previousIsLowerOrDigit || nextIsLower))
                    sb.Append('_');

                sb.Append(char.ToLowerInvariant(current));
            }
            else
            {
                sb.Append(current);
            }
        }

        return sb.ToString();
    }

    private static string SanitizeProtoIdentifier(string value)
    {
        if (string.IsNullOrWhiteSpace(value))
            return "_";

        var sb = new StringBuilder();

        foreach (var c in value)
            sb.Append(char.IsLetterOrDigit(c) || c == '_' ? c : '_');

        if (char.IsDigit(sb[0]))
            sb.Insert(0, '_');

        return sb.ToString();
    }

    private static string SanitizeQualifiedProtoName(string value)
    {
        return string.Join(
            ".",
            value.Split('.').Select(SanitizeProtoIdentifier));
    }

    private static string EscapeProtoString(string value)
    {
        return value
            .Replace("\\", "\\\\")
            .Replace("\"", "\\\"")
            .Replace("\r", "\\r")
            .Replace("\n", "\\n");
    }

    private static string EscapeCSharpIdentifier(string value)
    {
        return SyntaxFacts.GetKeywordKind(value) != SyntaxKind.None
            ? $"@{value}"
            : value;
    }
}
